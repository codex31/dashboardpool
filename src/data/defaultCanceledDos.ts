/**
 * Extracts all cancelled DOs from raw daily sheets data
 */
export function extractCanceledDosFromDaysData(
  daysData: Array<{ day: number; csv: string }>,
  monthName = 'Sep',
  year = 2026
): CancelledDoItem[] {
  const result: CancelledDoItem[] = [];

  for (const item of daysData) {
    if (!item.csv || item.csv.length < 50) continue;
    const lines = item.csv.split('\n');
    let headerIdx = -1;

    for (let i = 0; i < Math.min(lines.length, 35); i++) {
      const lineUpper = lines[i].toUpperCase();
      if (lineUpper.includes('NAMA TEAM YANG JALUR')) {
        headerIdx = i;
        break;
      }
    }

    if (headerIdx === -1) continue;

    const dateFormatted = `${String(item.day).padStart(2, '0')} ${monthName} ${year}`;

    for (let i = headerIdx + 1; i < lines.length; i++) {
      const line = lines[i];
      if (!line || line.trim().length === 0) continue;
      
      const parts = line.split(',').map((p) => p.replace(/^"|"$/g, '').trim());
      if (parts.length < 6) continue;

      const noDo = parts[2];
      const team = parts[3];
      const bobotStr = (parts[4] || '0').replace(',', '.');
      const bobot = parseFloat(bobotStr) || 0;
      const status = (parts[5] || '').toUpperCase();
      const kategori = parts[1] || 'REGULER';
      const reason = parts[26] || parts[8] || 'Cancel Order';

      if (!noDo || noDo === '-' || noDo.toUpperCase().includes('TOTAL')) continue;

      if (status === 'CANCEL') {
        result.push({
          id: `cancel-${item.day}-${noDo}`,
          dayNumber: item.day,
          tanggal: dateFormatted,
          noDo,
          kategori,
          teamName: team || 'Pool Team',
          bobot,
          status: 'CANCEL',
          reason: reason || 'Cancel Order',
        });
      }
    }
  }

  // Sort latest to oldest (descending by day)
  return result.sort((a, b) => b.dayNumber - a.dayNumber);
}

