/**
 * Filter cancelled DOs for a specific date or day number
 */
export function getCanceledDosForDate(
  canceledList: CancelledDoItem[],
  dateStrOrDay: string | number
): CancelledDoItem[] {
  if (typeof dateStrOrDay === 'number') {
    return canceledList.filter((c) => c.dayNumber === dateStrOrDay);
  }

  const clean = dateStrOrDay.toLowerCase().trim();
  // Try matching day number e.g. "05" or "5" or matching full string
  const dayMatch = clean.match(/^0?(\d+)/);
  const targetDay = dayMatch ? parseInt(dayMatch[1], 10) : null;

  return canceledList.filter((c) => {
    if (c.tanggal.toLowerCase().includes(clean) || clean.includes(c.tanggal.toLowerCase())) {
      return true;
    }
    if (targetDay !== null && c.dayNumber === targetDay) {
      return true;
    }
    return false;
  });
}
